//! Connect tokens: how a client proves it may join a server (the netcode design, ADR 0070).
//!
//! Whoever decides that a player may join (a matchmaker, a lobby service, or the host of a
//! co-op game itself) shares a private key with the server and generates a token per
//! player. The token's private part is sealed with that key; the client cannot read or
//! change it, only present it. The public part gives the client the server addresses and
//! the two packet keys, so the token itself is a secret: deliver it over an authenticated,
//! encrypted channel (HTTPS, the platform's lobby or invite system).

use std::net::SocketAddr;

use crate::bytes::{Reader, Writer};
use crate::crypto::{Cipher, KEY_BYTES, Key, NONCE_BYTES, TAG_BYTES, random_bytes};

/// The protocol's version tag, bound into every token and packet.
pub const VERSION: [u8; 8] = *b"OFNET001";
/// Bytes of a serialized [`ConnectToken`].
pub const CONNECT_TOKEN_BYTES: usize = 2048;
/// Bytes of the sealed private part, tag included.
pub(crate) const PRIVATE_TOKEN_BYTES: usize = 1024;
/// At most this many server addresses in a token.
pub const MAX_SERVER_ADDRESSES: usize = 8;
/// Bytes of application data the token carries to the server (account id, cosmetics...).
pub const USER_DATA_BYTES: usize = 256;
/// Bytes of a sealed challenge token, tag included.
pub(crate) const CHALLENGE_TOKEN_BYTES: usize = 300;

/// Why a token could not be made or read.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum TokenError {
    /// No server address, or more than [`MAX_SERVER_ADDRESSES`].
    #[error("a token needs 1 to {MAX_SERVER_ADDRESSES} server addresses")]
    Addresses,
    /// The bytes are not a token of this version.
    #[error("not a connect token of this version")]
    Malformed,
}

/// A fixed list of up to [`MAX_SERVER_ADDRESSES`] addresses.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct AddressList {
    addrs: [SocketAddr; MAX_SERVER_ADDRESSES],
    len: u8,
}

impl AddressList {
    /// A list of `addrs`, or `None` if there are none or too many.
    pub fn new(addrs: &[SocketAddr]) -> Option<Self> {
        if addrs.is_empty() || addrs.len() > MAX_SERVER_ADDRESSES {
            return None;
        }
        let mut list = Self {
            addrs: [addrs[0]; MAX_SERVER_ADDRESSES],
            len: addrs.len() as u8,
        };
        list.addrs[..addrs.len()].copy_from_slice(addrs);
        Some(list)
    }

    /// The addresses.
    pub fn as_slice(&self) -> &[SocketAddr] {
        &self.addrs[..usize::from(self.len)]
    }

    fn write(&self, w: &mut Writer<'_>) -> Option<()> {
        w.u8(self.len)?;
        for addr in self.as_slice() {
            w.addr(*addr)?;
        }
        Some(())
    }

    fn read(r: &mut Reader<'_>) -> Option<Self> {
        let len = usize::from(r.u8()?);
        if len == 0 || len > MAX_SERVER_ADDRESSES {
            return None;
        }
        let first = r.addr()?;
        let mut list = Self {
            addrs: [first; MAX_SERVER_ADDRESSES],
            len: len as u8,
        };
        for slot in &mut list.addrs[1..len] {
            *slot = r.addr()?;
        }
        Some(list)
    }
}

/// What a token grants: generated by the side that admits players.
#[derive(Clone, Debug)]
pub struct TokenParams<'a> {
    /// The game and protocol revision: a client and server only talk with equal ids.
    /// Change it whenever the channel layout or message formats change.
    pub protocol_id: u64,
    /// The player's id, unique on the server (an account id, or random).
    pub client_id: u64,
    /// How long the token may be used to start connecting, in seconds (netcode uses 30).
    pub expire_seconds: u64,
    /// Seconds without packets before either side drops the connection (default 10).
    pub timeout_seconds: u32,
    /// Where the client may find the server, tried in order. The server only accepts the
    /// token if one of them is among its own addresses (`ServerConfig::public_addresses`).
    pub server_addresses: &'a [SocketAddr],
    /// Data for the server, readable only by it.
    pub user_data: [u8; USER_DATA_BYTES],
}

/// A connect token as the client holds it.
#[derive(Clone, Debug)]
pub struct ConnectToken {
    /// See [`TokenParams::protocol_id`].
    pub protocol_id: u64,
    /// Unix time of creation, seconds.
    pub create_timestamp: u64,
    /// Unix time after which the server refuses the token, seconds.
    pub expire_timestamp: u64,
    pub(crate) nonce: [u8; NONCE_BYTES],
    pub(crate) private: [u8; PRIVATE_TOKEN_BYTES],
    /// See [`TokenParams::timeout_seconds`].
    pub timeout_seconds: u32,
    /// See [`TokenParams::server_addresses`].
    pub server_addresses: AddressList,
    pub(crate) client_to_server_key: Key,
    pub(crate) server_to_client_key: Key,
}

/// The sealed part, as the server reads it.
#[derive(Clone, Debug)]
pub(crate) struct PrivateToken {
    pub(crate) client_id: u64,
    pub(crate) timeout_seconds: u32,
    pub(crate) server_addresses: AddressList,
    pub(crate) client_to_server_key: Key,
    pub(crate) server_to_client_key: Key,
    pub(crate) user_data: [u8; USER_DATA_BYTES],
}

/// Additional data the private part is bound to: version, protocol id, expiry.
fn private_aad(protocol_id: u64, expire_timestamp: u64) -> [u8; 24] {
    let mut aad = [0u8; 24];
    aad[..8].copy_from_slice(&VERSION);
    aad[8..16].copy_from_slice(&protocol_id.to_le_bytes());
    aad[16..].copy_from_slice(&expire_timestamp.to_le_bytes());
    aad
}

/// The current Unix time in seconds.
pub fn unix_now() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_secs())
}

impl ConnectToken {
    /// Generates a token sealed with `private_key` (shared only with the servers), at Unix
    /// time `now` (seconds; [`unix_now`]).
    ///
    /// The nonce is random (96 bits): one private key must not seal more than 2^32 tokens
    /// (NIST SP 800-38D). Rotate the key long before that.
    ///
    /// ```
    /// use engine_net_transport::{ConnectToken, Key, TokenParams, unix_now};
    /// let key = Key::random();
    /// let server = "203.0.113.7:27015".parse().unwrap();
    /// let token = ConnectToken::generate(
    ///     &TokenParams {
    ///         protocol_id: 0x0f1e_0001,
    ///         client_id: 42,
    ///         expire_seconds: 30,
    ///         timeout_seconds: 10,
    ///         server_addresses: &[server],
    ///         user_data: [0; 256],
    ///     },
    ///     &key,
    ///     unix_now(),
    /// )
    /// .unwrap();
    /// let mut bytes = [0u8; engine_net_transport::CONNECT_TOKEN_BYTES];
    /// token.write(&mut bytes);
    /// assert_eq!(ConnectToken::read(&bytes).unwrap().server_addresses.as_slice(), &[server]);
    /// ```
    pub fn generate(
        params: &TokenParams<'_>,
        private_key: &Key,
        now: u64,
    ) -> Result<Self, TokenError> {
        let addresses = AddressList::new(params.server_addresses).ok_or(TokenError::Addresses)?;
        let client_to_server_key = Key::random();
        let server_to_client_key = Key::random();
        let expire_timestamp = now.saturating_add(params.expire_seconds);
        let mut nonce = [0u8; NONCE_BYTES];
        random_bytes(&mut nonce);

        let mut private = [0u8; PRIVATE_TOKEN_BYTES];
        let mut w = Writer::new(&mut private[..PRIVATE_TOKEN_BYTES - TAG_BYTES]);
        // The plaintext fits by construction: 8 + 4 + 1 + 8 * 19 + 64 + 256 < 1008.
        let fits = (|| {
            w.u64(params.client_id)?;
            w.u32(params.timeout_seconds)?;
            addresses.write(&mut w)?;
            w.bytes(&client_to_server_key.0)?;
            w.bytes(&server_to_client_key.0)?;
            w.bytes(&params.user_data)
        })();
        debug_assert!(fits.is_some());
        Cipher::new(private_key).seal_append(
            &nonce,
            &private_aad(params.protocol_id, expire_timestamp),
            &mut private,
            PRIVATE_TOKEN_BYTES - TAG_BYTES,
        );
        Ok(Self {
            protocol_id: params.protocol_id,
            create_timestamp: now,
            expire_timestamp,
            nonce,
            private,
            timeout_seconds: params.timeout_seconds,
            server_addresses: addresses,
            client_to_server_key,
            server_to_client_key,
        })
    }

    /// Serializes the token (zero-padded to [`CONNECT_TOKEN_BYTES`]).
    pub fn write(&self, out: &mut [u8; CONNECT_TOKEN_BYTES]) {
        out.fill(0);
        let mut w = Writer::new(out);
        // 8 + 24 + 12 + 1024 + 4 + 153 + 64 < 2048.
        let fits = (|| {
            w.bytes(&VERSION)?;
            w.u64(self.protocol_id)?;
            w.u64(self.create_timestamp)?;
            w.u64(self.expire_timestamp)?;
            w.bytes(&self.nonce)?;
            w.bytes(&self.private)?;
            w.u32(self.timeout_seconds)?;
            self.server_addresses.write(&mut w)?;
            w.bytes(&self.client_to_server_key.0)?;
            w.bytes(&self.server_to_client_key.0)
        })();
        debug_assert!(fits.is_some());
    }

    /// Reads a serialized token.
    pub fn read(bytes: &[u8]) -> Result<Self, TokenError> {
        if bytes.len() != CONNECT_TOKEN_BYTES {
            return Err(TokenError::Malformed);
        }
        let mut r = Reader::new(bytes);
        (|| {
            if r.array::<8>()? != VERSION {
                return None;
            }
            Some(Self {
                protocol_id: r.u64()?,
                create_timestamp: r.u64()?,
                expire_timestamp: r.u64()?,
                nonce: r.array()?,
                private: r.array()?,
                timeout_seconds: r.u32()?,
                server_addresses: AddressList::read(&mut r)?,
                client_to_server_key: Key(r.array()?),
                server_to_client_key: Key(r.array()?),
            })
        })()
        .ok_or(TokenError::Malformed)
    }
}

impl PrivateToken {
    /// Opens a sealed private part in place.
    pub(crate) fn open(
        cipher: &Cipher,
        protocol_id: u64,
        expire_timestamp: u64,
        nonce: &[u8; NONCE_BYTES],
        sealed: &mut [u8; PRIVATE_TOKEN_BYTES],
    ) -> Option<Self> {
        let len = cipher
            .open_appended(nonce, &private_aad(protocol_id, expire_timestamp), sealed)
            .ok()?;
        let mut r = Reader::new(&sealed[..len]);
        Some(Self {
            client_id: r.u64()?,
            timeout_seconds: r.u32()?,
            server_addresses: AddressList::read(&mut r)?,
            client_to_server_key: Key(r.array::<KEY_BYTES>()?),
            server_to_client_key: Key(r.array::<KEY_BYTES>()?),
            user_data: r.array()?,
        })
    }
}

/// Seals the challenge token: proves to the server, on the client's response, that the
/// client received the challenge at its claimed address (no state needed before that
/// beyond the pending keys).
pub(crate) fn seal_challenge(
    cipher: &Cipher,
    sequence: u64,
    client_id: u64,
    user_data: &[u8; USER_DATA_BYTES],
    out: &mut [u8; CHALLENGE_TOKEN_BYTES],
) {
    out.fill(0);
    out[..8].copy_from_slice(&client_id.to_le_bytes());
    out[8..8 + USER_DATA_BYTES].copy_from_slice(user_data);
    cipher.seal_append(
        &crate::crypto::sequence_nonce(sequence),
        &VERSION,
        out,
        CHALLENGE_TOKEN_BYTES - TAG_BYTES,
    );
}

/// Opens a challenge token: the client id and user data.
pub(crate) fn open_challenge(
    cipher: &Cipher,
    sequence: u64,
    sealed: &mut [u8; CHALLENGE_TOKEN_BYTES],
) -> Option<(u64, [u8; USER_DATA_BYTES])> {
    cipher
        .open_appended(&crate::crypto::sequence_nonce(sequence), &VERSION, sealed)
        .ok()?;
    let mut r = Reader::new(&sealed[..]);
    Some((r.u64()?, r.array()?))
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]
    use super::*;

    fn params(addrs: &[SocketAddr]) -> TokenParams<'_> {
        TokenParams {
            protocol_id: 0x1234,
            client_id: 77,
            expire_seconds: 30,
            timeout_seconds: 10,
            server_addresses: addrs,
            user_data: [9; USER_DATA_BYTES],
        }
    }

    #[test]
    fn tokens_round_trip_and_open_only_with_the_key() {
        let key = Key::random();
        let addrs: [SocketAddr; 2] = [
            "127.0.0.1:4000".parse().unwrap(),
            "[::1]:4000".parse().unwrap(),
        ];
        let token = ConnectToken::generate(&params(&addrs), &key, 1_000).unwrap();
        assert_eq!(token.expire_timestamp, 1_030);
        let mut bytes = [0u8; CONNECT_TOKEN_BYTES];
        token.write(&mut bytes);
        let read = ConnectToken::read(&bytes).unwrap();
        assert_eq!(read.server_addresses.as_slice(), &addrs);
        assert_eq!(read.client_to_server_key, token.client_to_server_key);

        let mut sealed = read.private;
        let private =
            PrivateToken::open(&Cipher::new(&key), 0x1234, 1_030, &read.nonce, &mut sealed)
                .unwrap();
        assert_eq!(private.client_id, 77);
        assert_eq!(private.server_addresses.as_slice(), &addrs);
        assert_eq!(private.server_to_client_key, token.server_to_client_key);
        assert_eq!(private.user_data, [9; USER_DATA_BYTES]);

        // Wrong key, wrong protocol, extended expiry, flipped byte: all refused.
        let mut sealed = read.private;
        assert!(
            PrivateToken::open(
                &Cipher::new(&Key::random()),
                0x1234,
                1_030,
                &read.nonce,
                &mut sealed
            )
            .is_none()
        );
        let mut sealed = read.private;
        assert!(
            PrivateToken::open(&Cipher::new(&key), 0x1235, 1_030, &read.nonce, &mut sealed)
                .is_none()
        );
        let mut sealed = read.private;
        assert!(
            PrivateToken::open(&Cipher::new(&key), 0x1234, 9_999, &read.nonce, &mut sealed)
                .is_none()
        );
        let mut sealed = read.private;
        sealed[100] ^= 1;
        assert!(
            PrivateToken::open(&Cipher::new(&key), 0x1234, 1_030, &read.nonce, &mut sealed)
                .is_none()
        );
    }

    #[test]
    fn address_limits_and_malformed_tokens() {
        let key = Key::random();
        assert_eq!(
            ConnectToken::generate(&params(&[]), &key, 0).unwrap_err(),
            TokenError::Addresses
        );
        let many = ["127.0.0.1:1".parse().unwrap(); 9];
        assert_eq!(
            ConnectToken::generate(&params(&many), &key, 0).unwrap_err(),
            TokenError::Addresses
        );
        assert!(ConnectToken::read(&[0u8; 10]).is_err());
        assert!(ConnectToken::read(&[0u8; CONNECT_TOKEN_BYTES]).is_err());
    }

    #[test]
    fn challenge_tokens_round_trip() {
        let cipher = Cipher::new(&Key::random());
        let mut sealed = [0u8; CHALLENGE_TOKEN_BYTES];
        seal_challenge(&cipher, 5, 99, &[3; USER_DATA_BYTES], &mut sealed);
        let mut copy = sealed;
        assert_eq!(open_challenge(&cipher, 5, &mut copy).unwrap().0, 99);
        let mut copy = sealed;
        assert!(open_challenge(&cipher, 6, &mut copy).is_none());
    }
}
